-- Esquema base para instalaciones nuevas.
-- No edites esta migración después de aplicarla; crea una nueva versión.

CREATE TABLE IF NOT EXISTS quotations (
  id VARCHAR(36) PRIMARY KEY DEFAULT (UUID()),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  company_name VARCHAR(255) NOT NULL,
  company_nit VARCHAR(50) NOT NULL,
  company_address TEXT,
  company_phone VARCHAR(50),
  company_email VARCHAR(255),
  client_name VARCHAR(255) NOT NULL,
  client_nit VARCHAR(50),
  client_address TEXT,
  client_phone VARCHAR(50),
  client_email VARCHAR(255),
  products JSON NOT NULL,
  subtotal DECIMAL(10, 2) NOT NULL,
  iva DECIMAL(10, 2) NOT NULL DEFAULT 0,
  total DECIMAL(10, 2) NOT NULL,
  delivery_time TEXT,
  warranty TEXT,
  observations TEXT,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  work_start_date DATE,
  work_end_date DATE,
  pdf_url TEXT,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS free_documents (
  id VARCHAR(36) PRIMARY KEY DEFAULT (UUID()),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  document_title VARCHAR(255) NOT NULL DEFAULT 'COTIZACION',
  document_number VARCHAR(100),
  company_name VARCHAR(255) NOT NULL,
  company_nit VARCHAR(50),
  company_address TEXT,
  company_phone VARCHAR(50),
  company_email VARCHAR(255),
  client_name VARCHAR(255) NOT NULL,
  client_nit VARCHAR(50),
  client_address TEXT,
  client_phone VARCHAR(50),
  client_email VARCHAR(255),
  general_description TEXT,
  items JSON NOT NULL,
  total DECIMAL(10, 2) NOT NULL,
  delivery_days INT DEFAULT 0,
  warranty_months INT DEFAULT 0,
  notes TEXT,
  document_date DATE,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS invoices (
  id VARCHAR(36) PRIMARY KEY DEFAULT (UUID()),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  quotation_id VARCHAR(36),
  free_document_id VARCHAR(36),
  company_name VARCHAR(255) NOT NULL,
  company_nit VARCHAR(50) NOT NULL,
  company_address TEXT,
  company_phone VARCHAR(50),
  company_email VARCHAR(255),
  client_name VARCHAR(255) NOT NULL,
  client_nit VARCHAR(50),
  client_address TEXT,
  client_phone VARCHAR(50),
  client_email VARCHAR(255),
  products JSON NOT NULL,
  subtotal DECIMAL(10, 2) NOT NULL,
  iva DECIMAL(10, 2) NOT NULL DEFAULT 0,
  total DECIMAL(10, 2) NOT NULL,
  work_description TEXT,
  work_start_date DATE,
  work_end_date DATE,
  payment_date DATE,
  payment_method VARCHAR(100),
  pdf_url TEXT,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_invoices_quotation FOREIGN KEY (quotation_id) REFERENCES quotations(id) ON DELETE SET NULL,
  CONSTRAINT fk_invoices_free_document FOREIGN KEY (free_document_id) REFERENCES free_documents(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
